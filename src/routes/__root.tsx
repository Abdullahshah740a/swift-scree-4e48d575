function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const location = useRouter().state.location.pathname;
  // Chromeless viewer route: no app header/footer.
  const isChromeless = location.startsWith("/v/");

  return (
    <QueryClientProvider client={queryClient}>
      {isChromeless ? (
        <Outlet />
      ) : (
        <AppShell>
          <Outlet />
        </AppShell>
      )}
    </QueryClientProvider>
  );
}
